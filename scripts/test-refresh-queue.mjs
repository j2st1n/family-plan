import assert from 'node:assert/strict';
import { createRefreshQueue, nextRefreshOrder } from '../src/parent-web/src/utils/refreshQueue.js';
let now = 10, calls = 0, release;
const queue = createRefreshQueue(() => now);
const pending = queue('day', async () => { calls++; await new Promise(resolve => { release = resolve; }); });
await Promise.resolve();
assert.equal(queue('day', () => { calls++; }, { observedAt: 9 }), pending);
assert.equal(calls, 1);
now = 20;
queue('day', () => { calls++; }, { observedAt: 11 });
queue('day', () => { calls++; }, { observedAt: 12 });
release(); await pending;
assert.equal(calls, 2, 'events after an older read require one follow-up');
await queue('day', () => { calls++; }, { observedAt: 19 });
assert.equal(calls, 2, 'successful newer read covers an earlier event');
await queue('day', () => { calls++; }, { observedAt: 20 });
assert.equal(calls, 3, 'equal timestamps must not discard an event');
await queue('failed', () => false);
await queue('failed', () => { calls++; }, { observedAt: 19 });
assert.equal(calls, 4, 'failed reads cannot satisfy later triggers');
await assert.rejects(queue('throws', () => { throw Error('synthetic'); }));
await queue('throws', () => { calls++; });
await queue('another-day', () => { calls++; }, { observedAt: 0 });
assert.equal(calls, 6);
const ordered = createRefreshQueue(), observedAt = nextRefreshOrder();
await ordered('same-tick', () => { calls++; });
await ordered('same-tick', () => { calls++; }, { observedAt });
assert.equal(calls, 7, 'logical ordering deduplicates without depending on browser clock precision');
console.log('refresh queue: causal ordering, coalescing, failure retry and independent keys passed');
